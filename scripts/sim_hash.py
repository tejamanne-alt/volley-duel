#!/usr/bin/env python3
"""Sim version hash: fingerprints the deterministic sim source code.

Both phones must run identical sim code; the handshake compares SimVersion (this hash +
the data hash + the state layout version) and refuses mismatched builds. The hash covers
every .cs file of Duel.Core.Sim and VolleyDuel.Sim, sorted by path, with LF line endings.

  python3 scripts/sim_hash.py --write   # regenerate Assets/VolleyDuel/Sim/SimCodeHash.g.cs
  python3 scripts/sim_hash.py --check   # exit 1 if the generated file is stale
"""
import hashlib, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = ["Packages/com.duel.core/Runtime/Sim", "Assets/VolleyDuel/Sim"]
OUT = ROOT / "Assets/VolleyDuel/Sim/SimCodeHash.g.cs"

def compute():
    files = []
    for d in DIRS:
        files += [p for p in (ROOT / d).rglob("*.cs") if p.name != OUT.name]
    rel = sorted(p.relative_to(ROOT).as_posix() for p in files)
    h = hashlib.sha256()
    for r in rel:
        text = (ROOT / r).read_bytes().decode("utf-8").replace("\r\n", "\n")
        h.update((r + "\n" + text + "\n").encode("utf-8"))
    return int.from_bytes(h.digest()[:8], "little"), len(rel)

def render(value, count):
    return (
        "// <auto-generated> by scripts/sim_hash.py from " + str(count) + " sim source files. Do not edit. </auto-generated>\n"
        "namespace VolleyDuel.Sim\n{\n"
        "    /// <summary>Fingerprint of the deterministic sim sources (Duel.Core.Sim + VolleyDuel.Sim).</summary>\n"
        "    public static class SimCodeHash\n    {\n"
        "        public const ulong Value = 0x%016XUL;\n    }\n}\n" % value
    )

if __name__ == "__main__":
    value, count = compute()
    text = render(value, count)
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("sim hash", "ok" if ok else "STALE", hex(value))
        sys.exit(0 if ok else 1)
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
        print("sim hash updated", hex(value))
